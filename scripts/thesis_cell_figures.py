from pathlib import Path
from typing import Any, Dict, List

import numpy as np

from configs.registry import CHOMSKY_BY_HIERARCHY, MQAR_TASKS
from reporting.heatmap_data import (
    average_performance_per_model,
    build_heatmap_raw_matrix,
    build_heatmap_scaled_matrix,
    build_heatmap_solved_matrix,
    extract_early_stop_accuracy,
    mean_scaled_accuracy_per_model,
)
from reporting.thesis_manifest import labels, models_for, runs_for, seed_of
import visualization.heatmaps
from visualization.heatmaps import plot_grouped_heatmap_solved
from visualization.style import (
    THESIS_HEATMAP_CMAP,
    THESIS_TEXT_HEIGHT_IN,
    THESIS_TEXT_WIDTH_IN,
    heatmap_figsize,
)
from visualization.utils import save_or_show

REPO_ROOT = Path(__file__).resolve().parents[1]
EXPERIMENT = "E1_cell_stacks"
IMAGES_DIR = REPO_ROOT / "figures/plots"
TABLES_DIR = REPO_ROOT / "figures/tables"

MODEL_ORDER = models_for(EXPERIMENT)
MODEL_LABELS = labels()

GROUP_REGULAR, GROUP_DCF, GROUP_CS, GROUP_MQAR = "Regular", "DCF", "CS", "MQAR"
SELECTED_TASK_GROUPS = {
    GROUP_REGULAR: [
        "parity_check",
        "even_pairs",
        "cycle_navigation",
        "modular_arithmetic",
    ],
    GROUP_DCF: [
        "modular_arithmetic_brackets",
        "solve_equation",
    ],
    GROUP_CS: ["binary_multiplication"],
    GROUP_MQAR: list(MQAR_TASKS),
}
GROUP_TASKS = {
    GROUP_REGULAR: CHOMSKY_BY_HIERARCHY["regular"],
    GROUP_DCF: CHOMSKY_BY_HIERARCHY["dcf"],
    GROUP_CS: CHOMSKY_BY_HIERARCHY["cs"],
    GROUP_MQAR: list(MQAR_TASKS),
}
FULL_TASK_GROUPS = GROUP_TASKS

TASK_LABELS = {
    "parity_check": "Parity",
    "even_pairs": "Even pairs",
    "cycle_navigation": "Cycle nav.",
    "modular_arithmetic": "Mod. arith.",
    "modular_arithmetic_brackets": "Mod. arith. (brackets)",
    "reverse_string": "Reverse string",
    "solve_equation": "Solve equation",
    "stack_manipulation": "Stack manip.",
    "binary_addition": "Binary add.",
    "binary_multiplication": "Binary mult.",
    "bucket_sort": "Bucket sort",
    "compute_sqrt": "Compute sqrt",
    "duplicate_string": "Duplicate string",
    "missing_duplicate_string": "Missing dup. string",
    "odds_first": "Odds first",
    "mqar": "MQAR",
}


def _model_label(model_name: str, all_models=None) -> str:
    del all_models
    return MODEL_LABELS[model_name]


def _task_label(task_name: str) -> str:
    return TASK_LABELS.get(task_name, task_name)


def _mean_std_over_seeds(
    per_seed: Dict[int, Dict[str, float]],
) -> tuple[Dict[str, float], Dict[str, float]]:
    means: Dict[str, float] = {}
    stds: Dict[str, float] = {}
    for model in MODEL_ORDER:
        vals = np.array([
            values[model] for values in per_seed.values() if model in values
        ])
        means[model] = float(np.mean(vals))
        stds[model] = float(np.std(vals, ddof=1)) if len(vals) > 1 else 0.0
    return means, stds


def _write_aggregate_table(
    stats: List[tuple[str, Dict[str, float], Dict[str, float]]],
    solved: Dict[str, Dict[str, float]],
) -> None:
    lines = [
        r"% Generated by scripts/thesis_cell_figures.py. Do not edit by hand.",
        r"\begin{table}[!htbp]",
        r"    \centering",
        r"    \caption[Accuracy of the bare cell stacks]{Mean scaled accuracy of the five bare cell stacks, over all sixteen tasks (Overall) and by task group. The yLSTM stack runs at chunk size $\ell = 1$. Accuracy entries give the mean $\pm$ sample standard deviation of the five seed-level task averages. A task counts as solved when all five seeds meet the criterion in Section~\ref{sec:method:techniques:metrics}.}",
        r"    \label{tab:experiments:cells:aggregate}",
        r"    \footnotesize",
        r"    \setlength{\tabcolsep}{2pt}",
        f"    \\begin{{tabularx}}{{\\linewidth}}{{l*{{{len(stats)}}}{{>{{\\centering\\arraybackslash}}X}}c}}",
        r"        \toprule",
        "         & " + " & ".join(name for name, _, _ in stats) + r" & \shortstack{Tasks\\solved} \\",
        r"        \midrule",
    ]
    for model in MODEL_ORDER:
        row = [MODEL_LABELS[model].removesuffix(", bare stack")]
        for _, means, stds in stats:
            row.append(f"${means[model]:.3f}\\,{{\\pm}}\\,{stds[model]:.3f}$")
        tasks = solved[model]
        row.append(f"{sum(value == 1.0 for value in tasks.values())}/{len(tasks)}")
        lines.append("        " + " & ".join(row) + r" \\")
    lines += [
        r"        \bottomrule",
        r"    \end{tabularx}",
        r"\end{table}",
    ]
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    output = TABLES_DIR / "cell_stack_aggregate.tex"
    output.write_text("\n".join(lines) + "\n")
    print(f"  Wrote {output}")


def main() -> None:
    visualization.heatmaps._format_model_label = _model_label
    visualization.heatmaps._format_task_label = _task_label
    visualization.heatmaps._MODEL_ORDER = MODEL_ORDER

    runs = runs_for(EXPERIMENT)
    if not runs:
        raise SystemExit("No runs found")

    runs_by_seed: Dict[int, List[Dict[str, Any]]] = {}
    for run in runs:
        runs_by_seed.setdefault(seed_of(run), []).append(run)
    print(f"Loaded {len(runs)} runs across seeds {sorted(runs_by_seed)}")

    per_seed_full: Dict[int, Dict[str, float]] = {}
    per_seed_group: Dict[str, Dict[int, Dict[str, float]]] = {
        name: {} for name in GROUP_TASKS
    }
    for seed, seed_runs in runs_by_seed.items():
        matrix, _ = build_heatmap_scaled_matrix(seed_runs)
        per_seed_full[seed] = average_performance_per_model(matrix)
        for name, tasks in GROUP_TASKS.items():
            per_seed_group[name][seed] = mean_scaled_accuracy_per_model(
                matrix, tasks
            )

    full = _mean_std_over_seeds(per_seed_full)
    stats = [("Overall", *full)]
    for name in GROUP_TASKS:
        stats.append((name, *_mean_std_over_seeds(per_seed_group[name])))

    raw_results, _ = build_heatmap_raw_matrix(runs)
    scaled_results, scaled_std = build_heatmap_scaled_matrix(runs)
    n_seeds = len(runs_by_seed)
    ddof_factor = float(np.sqrt(n_seeds / (n_seeds - 1)))
    scaled_std = {
        model: {task: value * ddof_factor for task, value in task_values.items()}
        for model, task_values in scaled_std.items()
    }
    early_stop = extract_early_stop_accuracy(runs)

    solved, solved_counts = build_heatmap_solved_matrix(runs, early_stop)
    _write_aggregate_table(stats, solved)

    fig = plot_grouped_heatmap_solved(
        scaled_results,
        SELECTED_TASK_GROUPS,
        threshold=1.0,
        std_results=scaled_std,
        title=None,
        cmap=THESIS_HEATMAP_CMAP,
        colorbar_label="Scaled accuracy",
        solved_results=solved,
        annotation_suffix=solved_counts,
        figsize=heatmap_figsize(len(MODEL_ORDER), THESIS_TEXT_WIDTH_IN, 45),
        annotation_fontsize=8,
        check_fontsize=14,
        show_colorbar=True,
    )
    fig.axes[0].set_xlabel("")
    fig.axes[0].set_ylabel("")
    IMAGES_DIR.mkdir(parents=True, exist_ok=True)
    output = IMAGES_DIR / "cell_selected_scaled_accuracy_heatmap.pdf"
    save_or_show(fig, output)
    print(f"  Wrote {output}")

    fig = plot_grouped_heatmap_solved(
        scaled_results,
        FULL_TASK_GROUPS,
        threshold=1.0,
        std_results=scaled_std,
        title=None,
        cmap=THESIS_HEATMAP_CMAP,
        colorbar_label="Scaled accuracy",
        solved_results=solved,
        annotation_suffix=solved_counts,
        figsize=heatmap_figsize(len(MODEL_ORDER), THESIS_TEXT_HEIGHT_IN, 30),
        annotation_fontsize=6,
        check_fontsize=12,
        show_colorbar=True,
        tick_rotation=30,
    )
    fig.axes[0].set_xlabel("")
    fig.axes[0].set_ylabel("")
    output = IMAGES_DIR / "cell_full_scaled_accuracy_heatmap.pdf"
    save_or_show(fig, output)
    print(f"  Wrote {output}")

    print("\n=== Bare cell stacks ===")
    for model in MODEL_ORDER:
        print(f"  {model:8s} overall {full[0][model]:.3f} +/- {full[1][model]:.3f}")
        for task in [t for ts in FULL_TASK_GROUPS.values() for t in ts]:
            if task in scaled_results.get(model, {}):
                print(
                    f"      {task:28s} scaled {scaled_results[model][task]:.3f} "
                    f"+/- {scaled_std[model].get(task, 0.0):.3f} "
                    f"raw {raw_results[model][task]:.3f} "
                    f"({solved_counts[model][task]})"
                )


if __name__ == "__main__":
    main()
