import csv
from pathlib import Path
from typing import Dict, List, Tuple

from configs.registry import CHOMSKY_BY_HIERARCHY, MQAR_TASKS
from reporting.thesis_manifest import (
    entry,
    labels,
    lr_hpo_csvs,
    models_for,
    source_meta,
    source_summary_csv,
)

REPO_ROOT = Path(__file__).resolve().parents[1]
TABLES_DIR = REPO_ROOT / "figures/tables"

_LABELS = labels()
HEADLINE_CORE = [(m, _LABELS[m]) for m in models_for("E1_headline")]
EXPLORATORY = [
    (m, _LABELS[m]) for m in models_for("E1_yhlstm_appendix")
]
CELLS = [(m, _LABELS[m]) for m in models_for("E1_cell_stacks")]
CROSS = [(m, _LABELS[m]) for m in models_for("E2_block_cross") if m != "ylstm_hb"]
CHUNK = [(m, _LABELS[m]) for m in models_for("E3_chunk") if m != "ylstm_hb_c1"]
N_PUBLISHED = len(entry("E1_headline")["models"]["published"])
LAYER_ALTERNATING_CONTROL = "xlstm_hb"

TASK_LABELS = {
    "parity_check": "parity check",
    "even_pairs": "even pairs",
    "cycle_navigation": "cycle navigation",
    "modular_arithmetic": "modular arithmetic",
    "modular_arithmetic_brackets": "mod.\\ arith.\\ (brackets)",
    "reverse_string": "reverse string",
    "solve_equation": "solve equation",
    "stack_manipulation": "stack manipulation",
    "binary_addition": "binary addition",
    "binary_multiplication": "binary multiplication",
    "bucket_sort": "bucket sort",
    "compute_sqrt": "compute sqrt",
    "duplicate_string": "duplicate string",
    "missing_duplicate_string": "missing duplicate string",
    "odds_first": "odds first",
    "mqar": "MQAR",
}
LEVELS = [
    ("Regular", CHOMSKY_BY_HIERARCHY["regular"]),
    ("DCF", CHOMSKY_BY_HIERARCHY["dcf"]),
    ("CS", CHOMSKY_BY_HIERARCHY["cs"]),
    ("MQAR", MQAR_TASKS),
]
FORMAL_TASKS = [t for _, ts in LEVELS[:3] for t in ts]


def _read_lr_csv(path: Path, models: List[str]) -> Dict[Tuple[str, str], float]:
    out: Dict[Tuple[str, str], float] = {}
    with open(path) as f:
        for r in csv.DictReader(f):
            if r["model"] in models:
                out[(r["model"], r["task"])] = float(r["best_lr"])
    return out


def _fmt_lr(lr: float) -> str:
    mant, exp = f"{lr:.0e}".split("e")
    return f"{int(mant)}e{int(exp)}"


def _fmt_int(n: int) -> str:
    return f"{n:,}".replace(",", "\\,")


def _read_lr_sources(experiment_id: str, models: List[str]) -> Dict[Tuple[str, str], float]:
    out: Dict[Tuple[str, str], float] = {}
    csvs = lr_hpo_csvs(experiment_id)
    for m in models:
        out.update(_read_lr_csv(csvs[m], [m]))
    return out


def write_lr_grid() -> None:
    lrs: Dict[Tuple[str, str], float] = {}
    lrs.update(
        _read_lr_sources("E1_headline", [m for m, _ in HEADLINE_CORE])
    )
    lrs.update(
        _read_lr_sources(
            "E1_yhlstm_appendix", [m for m, _ in EXPLORATORY]
        )
    )
    lrs.update(_read_lr_sources("E1_cell_stacks", [m for m, _ in CELLS]))
    for m, meta in source_meta("E2_block_cross").items():
        if m in dict(CROSS):
            for t, lr in meta["best_lrs"][m].items():
                lrs[(m, t)] = float(lr)
    lrs.update(_read_lr_sources("E3_chunk", [m for m, _ in CHUNK]))

    cols = HEADLINE_CORE + EXPLORATORY + CELLS + CROSS + CHUNK
    non_published = [m for m, _ in HEADLINE_CORE[N_PUBLISHED:]]
    if non_published[-1] != LAYER_ALTERNATING_CONTROL:
        raise ValueError(
            "The layer-alternating control must be the last E1_headline "
            f"column so its header stays contiguous, got {non_published}."
        )
    groups = [
        ("Published blocks", N_PUBLISHED),
        ("hLSTM and yLSTM", len(non_published) - 1),
        ("Control", 1),
        ("Exploratory", len(EXPLORATORY)),
        ("Bare cell stacks", len(CELLS)),
        ("Block comparison", len(CROSS)),
        ("yLSTM chunk size", len(CHUNK)),
    ]
    heads, rules, col = [], [], 2
    for name, n in groups:
        heads.append(f"\\multicolumn{{{n}}}{{c}}{{{name}}}")
        rules.append(f"\\cmidrule(lr){{{col}-{col + n - 1}}}")
        col += n
    lines = [
        "% Generated by scripts/thesis_appendix_tables.py. Do not edit by hand.",
        "\\begin{tabular}{l" + "c" * len(cols) + "}",
        "    \\toprule",
        "    & " + " & ".join(heads) + " \\\\",
        "    " + " ".join(rules),
        "    Task & " + " & ".join(f"\\rotatebox{{90}}{{{lbl}}}" for _, lbl in cols) + " \\\\",
        "    \\midrule",
    ]
    for i, (level, tasks) in enumerate(LEVELS):
        if i:
            lines.append("    \\midrule")
        for t in tasks:
            cells = [_fmt_lr(lrs[(m, t)]) for m, _ in cols]
            lines.append(f"    {TASK_LABELS[t]} & " + " & ".join(cells) + " \\\\")
    lines += ["    \\bottomrule", "\\end{tabular}", ""]
    (TABLES_DIR / "lr_grid.tex").write_text("\n".join(lines))


def _counts(summary: Path, models: List[str]) -> Dict[str, Dict[str, int]]:
    per: Dict[str, Dict[str, set]] = {m: {} for m in models}
    with open(summary) as f:
        for r in csv.DictReader(f):
            if r["model"] in models:
                per[r["model"]].setdefault(r["task"], set()).add(int(float(r["parameters_trainable"])))
    out = {}
    for m, by_task in per.items():
        for t, s in by_task.items():
            assert len(s) == 1, (m, t, s)
        formal = [next(iter(by_task[t])) for t in FORMAL_TASKS]
        out[m] = {
            "formal_min": min(formal),
            "formal_max": max(formal),
            "recall": next(iter(by_task["mqar"])),
        }
    return out


def _widths(meta: dict, model: str) -> Dict[str, int]:
    mw = meta["param_matching"]["matched_widths"]
    return {basis: int(mw[basis][model]["hidden_dim"]) for basis in ("chomsky", "mqar")}


def write_param_budget() -> None:
    rows = HEADLINE_CORE + EXPLORATORY + CELLS + CROSS
    metas = {
        **source_meta("E1_headline"),
        **source_meta("E1_yhlstm_appendix"),
        **source_meta("E1_cell_stacks"),
        **source_meta("E2_block_cross"),
    }
    summaries = {
        **source_summary_csv("E1_headline"),
        **source_summary_csv("E1_yhlstm_appendix"),
        **source_summary_csv("E1_cell_stacks"),
        **source_summary_csv("E2_block_cross"),
    }

    widths = {m: _widths(metas[m], m) for m, _ in rows if m in metas and m not in ("lstm", "gru")}
    widths["lstm"] = {"chomsky": 64, "mqar": 64}
    widths["gru"] = {"chomsky": 74, "mqar": 74}

    counts = {}
    for summary in sorted(set(summaries.values())):
        counts.update(_counts(summary, [m for m, _ in rows if summaries[m] == summary]))
    lines = [
        "% Generated by scripts/thesis_appendix_tables.py. Do not edit by hand.",
        "\\begin{tabular}{lrrrrr}",
        "    \\toprule",
        "    & \\multicolumn{3}{c}{Formal language tasks} & \\multicolumn{2}{c}{MQAR} \\\\",
        "    \\cmidrule(lr){2-4} \\cmidrule(lr){5-6}",
        "    Architecture & Width & Min.\\ params & Max.\\ params & Width & Params \\\\",
        "    \\midrule",
    ]
    for i, (m, lbl) in enumerate(rows):
        if i in (
            N_PUBLISHED,
            len(HEADLINE_CORE),
            len(HEADLINE_CORE) + len(EXPLORATORY),
            len(HEADLINE_CORE) + len(EXPLORATORY) + len(CELLS),
        ):
            lines.append("    \\midrule")
        w, c = widths[m], counts[m]
        lines.append(
            f"    {lbl} & {w['chomsky']} & {_fmt_int(c['formal_min'])} & {_fmt_int(c['formal_max'])}"
            f" & {w['mqar']} & {_fmt_int(c['recall'])} \\\\"
        )
    lines += ["    \\bottomrule", "\\end{tabular}", ""]
    (TABLES_DIR / "param_budget.tex").write_text("\n".join(lines))


def main() -> None:
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    write_lr_grid()
    write_param_budget()
    print(f"Wrote lr_grid.tex and param_budget.tex to {TABLES_DIR}")


if __name__ == "__main__":
    main()
